import { existsSync, readFileSync, writeFileSync, appendFileSync, chmodSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { randomBytes } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { createInterface } from 'node:readline/promises';
import { fileURLToPath } from 'node:url';
import { readVars, localConfiguration } from './configuration.ts';
import { inspectConfiguration } from '../shared/config/index.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const project = args.includes('--directory') ? resolve(args[args.indexOf('--directory') + 1]) : process.cwd();
const envPath = resolve(project, '.dev.vars');
if (!existsSync(envPath)) writeFileSync(envPath, readFileSync(resolve(root, '.dev.vars.example')), { mode: 0o600, flag: 'wx' });
const vars = readVars(envPath);
let additions = '';
if (!vars.AUTH_SETUP_TOKEN || vars.AUTH_SETUP_TOKEN.length < 32) additions += `\nAUTH_SETUP_TOKEN=${randomBytes(32).toString('hex')}\n`;
if (!vars.AUTH_SESSION_SECRET) additions += `AUTH_SESSION_SECRET=${randomBytes(32).toString('hex')}\n`;
if (additions) appendFileSync(envPath, '\n# Generated by npm run setup\n' + additions);
chmodSync(envPath, 0o600);
console.log('Local environment prepared. Existing keys and model settings were preserved.');
console.log('The initialization code is AUTH_SETUP_TOKEN in .dev.vars; it is not printed here.');

const { env, config } = localConfiguration(resolve(project, 'wrangler.jsonc'));
const report = inspectConfiguration(env);
for (const issue of report.errors) console.error(`ERROR: ${issue.message}`);
if (report.errors.length) process.exit(1);

const run = (command: string[]) => {
  const result = spawnSync(process.execPath, [resolve(root, 'node_modules/wrangler/bin/wrangler.js'), ...command, '--config', resolve(project, 'wrangler.jsonc')], { cwd: project, stdio: 'inherit' });
  if (result.status !== 0) throw new Error('Wrangler command failed; fix the reported issue before continuing.');
};
if (args.includes('--local')) {
  run(['d1', 'migrations', 'apply', config.d1_databases[0].database_name, '--local']);
  console.log('Local database ready. Run npm run dev and create your administrator.');
} else if (args.includes('--cloudflare')) {
  // The CLI's OAuth login provisions resources; the deployed Worker does not receive this credential.
  run(['whoami']);
  const terminal = createInterface({ input: process.stdin, output: process.stdout });
  const confirm = await terminal.question('Confirm the displayed Cloudflare account. Type CREATE to create the database and R2 bucket listed in wrangler.jsonc: ');
  terminal.close();
  if (confirm !== 'CREATE') throw new Error('No Cloudflare resources were created.');
  run(['d1', 'create', config.d1_databases[0].database_name, '--update-config', '--binding', config.d1_databases[0].binding]);
  run(['r2', 'bucket', 'create', config.r2_buckets[0].bucket_name]);
  console.log('Resources created. Review the database ID, account and CNAME_TARGET, then follow docs/self-hosting.md to migrate and deploy.');
} else console.log('Next: npm run setup -- --local. For cloud resources use --cloudflare; it displays your account and asks before creating resources.');
